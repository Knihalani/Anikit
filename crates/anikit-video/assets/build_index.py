#!/usr/bin/env python3
"""Build `assets/index.json`, the curated starter index of CC0 assets.

Every file is pinned: URL, size and a checksum (Poly Haven's md5, or a
sha256 we compute by streaming the file once for sources that publish none).
Re-run to refresh; the output is deterministic for a given upstream state.

    python3 crates/anikit-video/assets/build_index.py [--no-hash]

Sources and licences (checked 2026-11-17):
  - Poly Haven  https://polyhaven.com/license        CC0 1.0 (all assets)
  - ambientCG   https://docs.ambientcg.com/license/  CC0 1.0 (all assets)
  - Khronos glTF-Sample-Assets: per-model metadata.json, only models whose
    every licence entry is CC0 are taken.
  - anikit LUTs: generated by anikit itself (CC0), no download.
"""
import hashlib, json, os, re, sys, urllib.request, concurrent.futures as cf

UA = {"User-Agent": "anikit-asset-index/1"}
HERE = os.path.dirname(os.path.abspath(__file__))
NOHASH = "--no-hash" in sys.argv


def get(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()


def js(url):
    return json.loads(get(url))


def sha256_of(url):
    h = hashlib.sha256()
    n = 0
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=600) as r:
        while True:
            b = r.read(1 << 20)
            if not b:
                break
            h.update(b)
            n += len(b)
    return h.hexdigest(), n


def one_line(s, name):
    s = (s or "").strip().replace("\n", " ")
    # Drop marketing boilerplate ("Free 24K unclipped HDRI capturing", "Model of a", "Texture:").
    for _ in range(12):
        s = re.sub(r"^[\s,:;\-–]*(free|unclipped|\d+K|HDRI|HDR|model|texture|photoscanned|scanned|high[- ]resolution|,|and)\b[\s,:;\-–]*", "", s, flags=re.I)
    s = re.sub(r"^[\s,:;\-–]+", "", s)
    s = re.sub(r"^(capturing|showing|of|with|featuring|depicting)\s+(an?\s+|the\s+)?", "", s, flags=re.I)
    s = re.sub(r"^(an?|the)\s+", "", s, flags=re.I)
    s = s.split(". ")[0].strip().rstrip(".")
    if len(s) < 8:
        s = name
    s = s[0].upper() + s[1:]
    if len(s) > 140:
        s = s[:140].rsplit(" ", 1)[0].rstrip(",;:-– ") + "…"
    return s


def tags_of(info, extra=()):
    t = []
    for x in list(info.get("categories", [])) + list(info.get("tags", [])) + list(extra):
        x = x.lower().strip()
        if x.startswith("collection:") or not x or x in t:
            continue
        t.append(x)
    return t[:14]


PH_LIC = {"license": "CC0-1.0", "licenseUrl": "https://polyhaven.com/license"}
ACG_LIC = {"license": "CC0-1.0", "licenseUrl": "https://docs.ambientcg.com/license/"}

# ---------------------------------------------------------------- Poly Haven


def pick(assets, buckets, n_total):
    """Most-downloaded assets per bucket (a bucket is a set of required categories)."""
    out = []
    for need, n in buckets:
        cands = [k for k, v in assets.items() if all(c in v["categories"] for c in need) and k not in out]
        cands.sort(key=lambda k: -assets[k]["download_count"])
        out += cands[:n]
    return out[:n_total]


def ph_hdris():
    a = js("https://api.polyhaven.com/assets?t=hdris")
    buckets = [
        (["studio"], 12), (["indoor"], 8), (["sunrise-sunset"], 9), (["midday", "clear"], 7),
        (["overcast"], 6), (["night"], 7), (["pure skies"], 6), (["urban"], 8), (["nature", "morning-afternoon"], 7),
    ]
    ids = pick(a, buckets, 70)
    out = []
    for k in ids:
        info = js(f"https://api.polyhaven.com/info/{k}")
        f = js(f"https://api.polyhaven.com/files/{k}")
        res = {}
        for r in ("1k", "2k", "4k"):
            h = f["hdri"].get(r, {}).get("hdr")
            if h:
                res[r] = [{"path": f"{k}_{r}.hdr", "url": h["url"], "size": h["size"], "md5": h["md5"]}]
        sun = "sun" in info.get("tags", []) or info.get("attributes", {}).get("weather") == "clear"
        e = {
            "id": f"polyhaven:hdri/{k}", "type": "hdri", "name": info["name"],
            "desc": one_line(info.get("description"), info["name"]),
            "tags": tags_of(info, [info.get("attributes", {}).get("time_of_day", "")]),
            "by": ", ".join(info.get("authors", {}).keys()), "page": f"https://polyhaven.com/a/{k}",
            "version": info.get("files_hash", "")[:12], **PH_LIC, "default": "1k", "res": res,
        }
        if sun:
            e["tags"].append("sun")
        out.append(e)
    return out


PH_MAPS = {"albedo": "Diffuse", "normal": "nor_gl", "roughness": "Rough", "ao": "AO", "displacement": "Displacement", "metalness": "Metal"}


def ph_textures():
    a = js("https://api.polyhaven.com/assets?t=textures")
    buckets = [
        (["wood"], 8), (["plaster-concrete"], 6), (["brick"], 5), (["rock"], 5), (["fabric"], 7), (["metal"], 6),
        (["tiles"], 4), (["floor", "indoor"], 3), (["sand"], 2), (["snow"], 1), (["leather"], 3), (["asphalt"], 2),
        (["bark"], 2), (["roofing"], 2), (["terrain"], 3), (["cobblestone"], 2),
    ]
    ids = pick(a, buckets, 62)
    out = []
    for k in ids:
        info = js(f"https://api.polyhaven.com/info/{k}")
        f = js(f"https://api.polyhaven.com/files/{k}")
        res = {}
        for r in ("1k", "2k"):
            files = []
            for role, key in PH_MAPS.items():
                h = f.get(key, {}).get(r, {}).get("jpg")
                if role == "displacement":
                    h = f.get(key, {}).get(r, {}).get("png") or h
                if h:
                    ext = h["url"].rsplit(".", 1)[1]
                    files.append({"path": f"{k}_{role}_{r}.{ext}", "url": h["url"], "size": h["size"], "md5": h["md5"], "role": role})
            if files:
                res[r] = files
        dim = info.get("dimensions")
        e = {
            "id": f"polyhaven:texture/{k}", "type": "texture", "name": info["name"],
            "desc": one_line(info.get("description"), info["name"]),
            "tags": tags_of(info), "by": ", ".join(info.get("authors", {}).keys()), "page": f"https://polyhaven.com/a/{k}",
            "version": info.get("files_hash", "")[:12], **PH_LIC, "default": "2k", "res": res,
        }
        if dim:
            e["size_m"] = round(dim[0] / 1000.0, 3)  # real-world width in metres
        out.append(e)
    return out


def ph_models():
    a = js("https://api.polyhaven.com/assets?t=models")
    buckets = [
        (["props"], 10), (["furniture"], 8), (["decorative"], 6), (["plants"], 5), (["electronics"], 3), (["food"], 3),
        (["rocks"], 2), (["lighting"], 2), (["containers"], 2), (["vases"], 2), (["instrument"], 1), (["trees"], 1),
    ]
    ids = pick(a, buckets, 42)
    out = []
    for k in ids:
        info = js(f"https://api.polyhaven.com/info/{k}")
        f = js(f"https://api.polyhaven.com/files/{k}")
        res = {}
        for r in ("1k", "2k"):
            g = f.get("gltf", {}).get(r, {}).get("gltf")
            if not g:
                continue
            files = [{"path": g["url"].rsplit("/", 1)[1], "url": g["url"], "size": g["size"], "md5": g["md5"], "role": "main"}]
            for p, h in sorted(g.get("include", {}).items()):
                files.append({"path": p, "url": h["url"], "size": h["size"], "md5": h["md5"]})
            res[r] = files
        if not res:
            continue
        tot = sum(x["size"] for x in res.get("1k", []))
        if tot > 60e6:
            continue
        e = {
            "id": f"polyhaven:model/{k}", "type": "model", "name": info["name"],
            "desc": one_line(info.get("description"), info["name"]),
            "tags": tags_of(info), "by": ", ".join(info.get("authors", {}).keys()), "page": f"https://polyhaven.com/a/{k}",
            "version": info.get("files_hash", "")[:12], **PH_LIC, "default": "1k", "res": res,
        }
        out.append(e)
    return out


# ---------------------------------------------------------------- ambientCG

ACG_CATS = [
    ("Marble", 3), ("Metal", 4), ("Fabric", 4), ("Paper", 2), ("Leather", 2), ("Tiles", 3), ("Wood", 4),
    ("Concrete", 3), ("PaintedPlaster", 1), ("Plastic", 2), ("Terrazzo", 2), ("Rock", 2), ("Ground", 2),
    ("Foam", 1), ("Carpet", 1), ("Rubber", 1), ("Bricks", 2), ("PaintedMetal", 1), ("Gravel", 1), ("Planks", 2),
    ("Travertine", 1), ("Chip", 1), ("Wicker", 1), ("Facade", 1), ("Snow", 1), ("Moss", 1),
]


def acg_materials():
    out = []
    seen = set()
    for cat, n in ACG_CATS:
        d = js(f"https://ambientcg.com/api/v2/full_json?type=Material&sort=Popular&limit={n * 3}&q={cat}&include=tagData,displayData,downloadData")
        got = 0
        for a in d["foundAssets"]:
            k = a["assetId"]
            if k in seen or not k.lower().startswith(cat.lower()) or got >= n:
                continue
            dls = {x["attribute"]: x for x in a["downloadFolders"]["default"]["downloadFiletypeCategories"].get("zip", {}).get("downloads", [])}
            res = {}
            for r, attr in (("1k", "1K-JPG"), ("2k", "2K-JPG")):
                x = dls.get(attr)
                if x:
                    res[r] = [{"path": x["fileName"], "url": x["downloadLink"], "size": x["size"], "unzip": True}]
            if "2k" not in res:
                continue
            seen.add(k)
            got += 1
            tags = []
            for t in [a["displayCategory"].lower()] + [t.lower() for t in a.get("tags", [])]:
                if not re.match(r"^\d+$", t) and t != k.lower() and t not in tags:
                    tags.append(t)
            name = a["displayName"]
            desc = a.get("description") or f"{a['displayCategory']} PBR material: {', '.join(tags[1:7]) or name}"
            out.append({
                "id": f"ambientcg:{k}", "type": "texture", "name": name, "desc": one_line(desc, name),
                "tags": tags[:12], "by": "ambientCG (Lennart Demes)",
                "page": a["shortLink"], "version": a["releaseDate"][:10], **ACG_LIC, "default": "2k", "res": res,
                "maps": a.get("maps", []),
                **({"size_m": round(a["dimensionX"] / 100.0, 3)} if a.get("dimensionX") else {}),
            })
    return out


# ---------------------------------------------------------------- Khronos CC0 models

KHRONOS_RAW = "https://raw.githubusercontent.com/KhronosGroup/glTF-Sample-Assets/main/Models"


def khronos_models():
    idx = js(f"{KHRONOS_RAW}/model-index.json")
    out = []
    for m in idx:
        name = m["name"]
        if "glTF-Binary" not in m.get("variants", {}):
            continue
        if any(t in m.get("tags", []) for t in ("testing", "issues")) or "Test" in name:
            continue
        try:
            meta = js(f"{KHRONOS_RAW}/{name}/metadata.json")
        except Exception:
            continue
        legal = meta.get("legal", [])
        if not legal or any("CC0" not in (l.get("license") or "") for l in legal):
            continue
        url = f"{KHRONOS_RAW}/{name}/glTF-Binary/{m['variants']['glTF-Binary']}"
        out.append({
            "id": f"khronos:{name}", "type": "model", "name": m["label"],
            "desc": one_line(meta.get("summary") or m["label"], m["label"]),
            "tags": [t.lower() for t in m.get("tags", [])] + ["khronos", "sample"],
            "by": ", ".join(sorted({l.get("artist", "") for l in legal if l.get("artist")})) or "Khronos Group",
            "page": f"https://github.com/KhronosGroup/glTF-Sample-Assets/tree/main/Models/{name}",
            "version": "main", "license": "CC0-1.0", "licenseUrl": legal[0].get("licenseUrl", "https://creativecommons.org/publicdomain/zero/1.0/"),
            "default": "glb", "res": {"glb": [{"path": f"{name}.glb", "url": url, "role": "main"}]},
        })
    return out


def fill_desc(e):
    """Assets without an upstream description: name plus what the tags say."""
    if e["desc"].strip().lower() == e["name"].strip().lower() and e["tags"]:
        kind = {"hdri": "HDRI", "texture": "texture", "model": "model"}.get(e["type"], e["type"])
        e["desc"] = f"{e['name']} ({kind}): " + ", ".join(e["tags"][:7])


def main():
    with cf.ThreadPoolExecutor(8) as ex:
        fs = {n: ex.submit(f) for n, f in [("hdri", ph_hdris), ("tex", ph_textures), ("model", ph_models), ("acg", acg_materials), ("khr", khronos_models)]}
        parts = {n: f.result() for n, f in fs.items()}
    entries = parts["hdri"] + parts["tex"] + parts["acg"] + parts["model"] + parts["khr"]
    # Files without a published checksum: hash them once.
    todo = [f for e in entries for fl in e["res"].values() for f in fl if "md5" not in f and "sha256" not in f]
    if not NOHASH:
        def h(f):
            try:
                s, n = sha256_of(f["url"])
                f["sha256"], f["size"] = s, n
            except Exception as ex:
                print("hash failed", f["url"], ex, file=sys.stderr)
        with cf.ThreadPoolExecutor(6) as ex:
            list(ex.map(h, todo))
    old = {}
    p = os.path.join(HERE, "index.json")
    for e in entries:
        fill_desc(e)
    entries.sort(key=lambda e: (e["type"], e["id"]))
    with open(p, "w") as fh:
        json.dump({"version": 1, "generated": "2026-11-17", "entries": entries}, fh, indent=None, separators=(",", ":"))
    by = {}
    for e in entries:
        by[e["type"]] = by.get(e["type"], 0) + 1
    print(len(entries), by, "unhashed:", sum(1 for f in todo if "sha256" not in f))


if __name__ == "__main__":
    main()
