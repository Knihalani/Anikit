//! 3D colour look-up tables: `.cube` files (Adobe/Resolve format) and a set of
//! film-style looks generated here (so they are ours, CC0, and cost no download).
//!
//! A LUT maps display-referred (sRGB-encoded) RGB in 0..1 to graded RGB; it is
//! applied by `post` after tone mapping (`"post": {"lut": "anikit:lut/teal-orange"}`).

use std::collections::HashMap;
use std::sync::{Arc, Mutex, OnceLock};

/// A cubic LUT: `n³` entries, red fastest (the `.cube` order).
#[derive(Clone, Debug, PartialEq)]
pub struct Lut {
    pub n: usize,
    pub data: Vec<[f32; 3]>,
    pub title: String,
}

impl Lut {
    /// Parse a `.cube` file (`LUT_3D_SIZE`, optional `DOMAIN_MIN`/`DOMAIN_MAX`, `TITLE`).
    pub fn parse_cube(text: &str) -> Result<Lut, String> {
        let (mut n, mut data, mut title) = (0usize, Vec::new(), String::new());
        let (mut lo, mut hi) = ([0.0f32; 3], [1.0f32; 3]);
        for (i, line) in text.lines().enumerate() {
            let l = line.trim();
            if l.is_empty() || l.starts_with('#') {
                continue;
            }
            let mut it = l.split_whitespace();
            let first = it.next().unwrap_or("");
            let nums = |it: std::str::SplitWhitespace| -> Result<[f32; 3], String> {
                let v: Vec<f32> = it.map(|x| x.parse::<f32>().map_err(|_| format!("line {}: bad number `{x}`", i + 1))).collect::<Result<_, _>>()?;
                v.get(..3).map(|s| [s[0], s[1], s[2]]).ok_or_else(|| format!("line {}: expected 3 numbers", i + 1))
            };
            match first {
                "TITLE" => title = l[5..].trim().trim_matches('"').to_string(),
                "LUT_3D_SIZE" => n = it.next().and_then(|x| x.parse().ok()).filter(|&n| (2..=256).contains(&n)).ok_or_else(|| format!("line {}: bad LUT_3D_SIZE", i + 1))?,
                "LUT_1D_SIZE" => return Err("1D LUTs aren't supported; use a 3D .cube".into()),
                "DOMAIN_MIN" => lo = nums(it)?,
                "DOMAIN_MAX" => hi = nums(it)?,
                "LUT_3D_INPUT_RANGE" | "LUT_1D_INPUT_RANGE" => {}
                _ if first.starts_with(|c: char| c.is_ascii_digit() || c == '-' || c == '.') => data.push(nums(l.split_whitespace())?),
                _ => {} // Unknown keywords are skipped, as Resolve does.
            }
        }
        if n == 0 {
            return Err("no LUT_3D_SIZE".into());
        }
        if data.len() != n * n * n {
            return Err(format!("expected {} entries for size {n}, found {}", n * n * n, data.len()));
        }
        if lo != [0.0; 3] || hi != [1.0; 3] {
            // Normalise outputs into 0..1 is not what DOMAIN means (it scales inputs);
            // we only support the default input domain.
            return Err("DOMAIN_MIN/MAX other than 0..1 aren't supported".into());
        }
        Ok(Lut { n, data, title })
    }

    /// Write as `.cube`.
    pub fn to_cube(&self) -> String {
        let mut s = format!("TITLE \"{}\"\n# Generated by anikit-video. CC0 1.0: no rights reserved.\nLUT_3D_SIZE {}\n", self.title, self.n);
        for c in &self.data {
            s += &format!("{:.6} {:.6} {:.6}\n", c[0], c[1], c[2]);
        }
        s
    }

    /// Trilinear lookup, input and output in 0..1 (display encoded).
    #[inline]
    pub fn sample(&self, c: [f32; 3]) -> [f32; 3] {
        let m = (self.n - 1) as f32;
        let mut i0 = [0usize; 3];
        let mut f = [0f32; 3];
        for k in 0..3 {
            let x = c[k].clamp(0.0, 1.0) * m;
            let i = (x as usize).min(self.n - 2);
            i0[k] = i;
            f[k] = x - i as f32;
        }
        let n = self.n;
        let at = |r: usize, g: usize, b: usize| self.data[r + n * (g + n * b)];
        let mut out = [0f32; 3];
        for (db, wb) in [(0, 1.0 - f[2]), (1, f[2])] {
            for (dg, wg) in [(0, 1.0 - f[1]), (1, f[1])] {
                for (dr, wr) in [(0, 1.0 - f[0]), (1, f[0])] {
                    let w = wr * wg * wb;
                    let v = at(i0[0] + dr, i0[1] + dg, i0[2] + db);
                    for k in 0..3 {
                        out[k] += v[k] * w;
                    }
                }
            }
        }
        out
    }

    fn generate(title: &str, n: usize, f: impl Fn([f32; 3]) -> [f32; 3]) -> Lut {
        let mut data = Vec::with_capacity(n * n * n);
        let m = (n - 1) as f32;
        for b in 0..n {
            for g in 0..n {
                for r in 0..n {
                    let o = f([r as f32 / m, g as f32 / m, b as f32 / m]);
                    data.push(o.map(|v| (v.clamp(0.0, 1.0) * 1e5).round() / 1e5));
                }
            }
        }
        Lut { n, data, title: title.into() }
    }
}

