/// A generated look as a 33³ LUT.
pub fn generated(name: &str) -> Option<Lut> {
    let f = film(name)?;
    Some(Lut::generate(name, 33, |c| f.eval(c)))
}

/// Load a LUT from an asset ref (`anikit:lut/teal-orange`), a bare look name,
/// or a `.cube` path; cached for the process.
pub fn load(src: &str) -> Result<Arc<Lut>, String> {
    static CACHE: OnceLock<Mutex<HashMap<String, Arc<Lut>>>> = OnceLock::new();
    let cache = CACHE.get_or_init(Default::default);
    if let Some(l) = cache.lock().unwrap().get(src) {
        return Ok(l.clone());
    }
    let name = src.strip_prefix("anikit:lut/").or_else(|| src.strip_prefix("lut/")).unwrap_or(src);
    let lut = if let Some(l) = generated(name) {
        l
    } else if super::is_ref(src) {
        let f = super::get(src)?;
        let text = std::fs::read_to_string(f.main()).map_err(|e| format!("{src}: {e}"))?;
        Lut::parse_cube(&text).map_err(|e| format!("{src}: {e}"))?
    } else if src.ends_with(".cube") {
        let text = std::fs::read_to_string(src).map_err(|e| format!("lut `{src}`: {e}"))?;
        Lut::parse_cube(&text).map_err(|e| format!("lut `{src}`: {e}"))?
    } else {
        let hint = crate::templates::suggest(name, LOOKS.iter().map(|l| l.0)).map(|s| format!(" (did you mean `anikit:lut/{s}`?)")).unwrap_or_default();
        return Err(format!("unknown lut `{src}`{hint}; built-in looks: {}; or a .cube file path", LOOKS.iter().map(|l| l.0).collect::<Vec<_>>().join(", ")));
    };
    let lut = Arc::new(lut);
    cache.lock().unwrap().insert(src.to_string(), lut.clone());
    Ok(lut)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_look_is_smooth_and_in_range() {
        for (name, _, _) in LOOKS {
            let l = generated(name).unwrap();
            assert_eq!(l.data.len(), 33 * 33 * 33);
            // Monotone-ish on the grey axis: brighter in → brighter out (luma).
            let mut last = -1.0;
            for i in 0..33 {
                let v = i as f32 / 32.0;
                let o = l.sample([v, v, v]);
                let y = luma(o);
                assert!(y >= last - 1e-3, "{name}: grey ramp not monotone at {v}");
                last = y;
            }
        }
    }

    #[test]
    fn cube_round_trip_and_identity() {
        let id = Lut::generate("id", 9, |c| c);
        let back = Lut::parse_cube(&id.to_cube()).unwrap();
        assert_eq!(back.n, 9);
        let c = back.sample([0.3, 0.6, 0.9]);
        assert!((c[0] - 0.3).abs() < 1e-4 && (c[1] - 0.6).abs() < 1e-4 && (c[2] - 0.9).abs() < 1e-4);
        assert!(Lut::parse_cube("LUT_3D_SIZE 2\n0 0 0\n").is_err());
    }

    #[test]
    fn looks_differ_from_identity() {
        let t = generated("teal-orange").unwrap();
        let skin = t.sample([0.8, 0.55, 0.42]);
        assert!(skin[0] - skin[2] > 0.8 - 0.42, "teal-orange should warm skin: {skin:?}");
        let m = generated("mono-silver").unwrap().sample([0.9, 0.1, 0.1]);
        assert!((m[0] - m[1]).abs() < 0.02 && (m[1] - m[2]).abs() < 0.02);
        assert!(load("anikit:lut/nope").is_err());
    }
}
