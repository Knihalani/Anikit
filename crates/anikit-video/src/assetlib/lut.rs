/// A parametric print look, evaluated in display space.
#[derive(Clone, Copy)]
struct Film {
    /// S-curve strength around `pivot` (0 = none).
    contrast: f32,
    pivot: f32,
    /// Black lift ("matte"/faded print) and white pull-down.
    fade: f32,
    roll: f32,
    sat: f32,
    /// Saturation multiplier in the highlights (film desaturates them).
    high_sat: f32,
    /// Split toning: added to shadows / highlights (signed, display units).
    shadows: [f32; 3],
    highs: [f32; 3],
    /// Per-channel gamma.
    gamma: [f32; 3],
    /// Pull skin/warm hues towards orange and cool hues towards teal (0..1).
    teal_orange: f32,
    /// Bleach bypass: blend in a contrasty luminance overlay (0..1).
    bleach: f32,
    /// Monochrome with this tint (multiplies luminance) when set.
    mono: Option<[f32; 3]>,
    /// Swap toward "day for night": darken, cool, desaturate.
    night: f32,
}

const NEUTRAL: Film = Film {
    contrast: 0.0,
    pivot: 0.45,
    fade: 0.0,
    roll: 0.0,
    sat: 1.0,
    high_sat: 1.0,
    shadows: [0.0; 3],
    highs: [0.0; 3],
    gamma: [1.0; 3],
    teal_orange: 0.0,
    bleach: 0.0,
    mono: None,
    night: 0.0,
};

fn luma(c: [f32; 3]) -> f32 {
    0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
}

fn smooth(x: f32) -> f32 {
    let x = x.clamp(0.0, 1.0);
    x * x * (3.0 - 2.0 * x)
}

impl Film {
    fn eval(&self, c0: [f32; 3]) -> [f32; 3] {
        let mut c: [f32; 3] = std::array::from_fn(|k| c0[k].max(0.0).powf(1.0 / self.gamma[k]));
        if self.night > 0.0 {
            let l = luma(c);
            let dn = [l * 0.55 + c[0] * 0.1, l * 0.75 + c[1] * 0.15, l * 0.95 + c[2] * 0.25];
            c = std::array::from_fn(|k| c[k] + (dn[k] * 0.62 - c[k]) * self.night);
        }
        if self.teal_orange > 0.0 {
            // Warm hues (r > b) go towards orange, cool hues towards teal, by chroma.
            let l = luma(c);
            let warm = (c[0] - c[2]).clamp(-1.0, 1.0);
            let t = self.teal_orange * (warm.abs() * 2.0).min(1.0);
            let target = if warm > 0.0 { [1.0, 0.62, 0.32] } else { [0.18, 0.55, 0.62] };
            let tn = luma(target);
            for k in 0..3 {
                let want = target[k] / tn * l;
                c[k] += (want - c[k]) * t * 0.5;
            }
            // Shadows lean teal, highlights warm: the classic split.
            let s = 1.0 - smooth(l / 0.5);
            let h = smooth((l - 0.5) / 0.5);
            c[0] += self.teal_orange * (-0.025 * s + 0.02 * h);
            c[1] += self.teal_orange * (0.01 * s + 0.005 * h);
            c[2] += self.teal_orange * (0.03 * s - 0.025 * h);
        }
        if self.contrast != 0.0 {
            for v in &mut c {
                // Sigmoid around the pivot, normalised so 0 → 0 and 1 → 1.
                let k = 1.0 + self.contrast * 4.0;
                let sig = |x: f32| 1.0 / (1.0 + (-(x - self.pivot) * k * 2.0).exp());
                let (a, b) = (sig(0.0), sig(1.0));
                let s = (sig(*v) - a) / (b - a);
                *v = *v + (s - *v) * self.contrast.signum() * self.contrast.abs().min(1.0);
            }
        }
        let l = luma(c);
        let hs = 1.0 + (self.high_sat - 1.0) * smooth((l - 0.55) / 0.45);
        let sat = self.sat * hs;
        c = c.map(|v| l + (v - l) * sat);
        if self.bleach > 0.0 {
            // Overlay of luminance on the image, mixed: silver retained.
            let ov = |a: f32, b: f32| if a < 0.5 { 2.0 * a * b } else { 1.0 - 2.0 * (1.0 - a) * (1.0 - b) };
            let l = luma(c);
            c = c.map(|v| {
                let o = ov(l, v);
                let m = l + (o - l) * 0.55;
                v + (m - v) * self.bleach
            });
        }
        if let Some(t) = self.mono {
            let l = luma(c);
            c = t.map(|k| l * k + (1.0 - k) * l * l * 0.0);
        }
        let l = luma(c).clamp(0.0, 1.0);
        let s = 1.0 - smooth(l / 0.55);
        let h = smooth((l - 0.45) / 0.55);
        std::array::from_fn(|k| self.fade + (c[k] + self.shadows[k] * s + self.highs[k] * h) * (1.0 - self.fade - self.roll))
    }
}

