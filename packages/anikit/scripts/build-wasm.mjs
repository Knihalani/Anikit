// Compile the Rust core to WebAssembly, optimise it with binaryen and embed it
// as base64 so `import "anikit"` works with zero bundler configuration.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');
const root = join(pkg, '..', '..');
const features = '+simd128,+bulk-memory,+nontrapping-fptoint,+sign-ext,+mutable-globals';

execFileSync('cargo', ['build', '-p', 'anikit-wasm', '--target', 'wasm32-unknown-unknown', '--profile', 'wasm'], {
  cwd: root,
  stdio: 'inherit',
  env: { ...process.env, RUSTFLAGS: `-C target-feature=${features}` },
});
const raw = join(root, 'target/wasm32-unknown-unknown/wasm/anikit_wasm.wasm');
const out = join(pkg, 'dist/anikit.wasm');
mkdirSync(join(pkg, 'dist'), { recursive: true });
try {
  execFileSync(process.execPath, [
    join(pkg, 'node_modules/binaryen/bin/wasm-opt'), '-O3', '--enable-simd', '--enable-bulk-memory',
    '--enable-nontrapping-float-to-int', '--enable-sign-ext', '--enable-mutable-globals', raw, '-o', out,
  ], { stdio: 'inherit' });
} catch {
  console.warn('wasm-opt unavailable, using unoptimised module');
  copyFileSync(raw, out);
}
const bytes = readFileSync(out);
mkdirSync(join(pkg, 'src/generated'), { recursive: true });
writeFileSync(
  join(pkg, 'src/generated/wasm-bytes.ts'),
  `// Generated by scripts/build-wasm.mjs — do not edit.\nexport const WASM_BASE64 =\n  '${bytes.toString('base64')}';\n`,
);
console.log(`wasm: ${bytes.length} bytes`);
