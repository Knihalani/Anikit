// Generate the component catalogue for the video builders from the renderer:
//   ANIKIT_VIDEO_BIN=target/release/anikit-video node packages/anikit/scripts/gen-video-components.mjs
// Writes packages/anikit/src/video/components.ts and crates/anikit-py/python/anikit/_video_components.py.
// A Rust test (anikit-video, templates::tests) fails when either misses a kind.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const bin = process.env.ANIKIT_VIDEO_BIN ?? 'anikit-video';
const { components } = JSON.parse(execFileSync(bin, ['info', '--components', '--json'], { encoding: 'utf8' }));
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const tsType = (v) => {
  if (Array.isArray(v)) {
    if (v.length && v.every((x) => typeof x === 'number')) return 'number[]';
    if (v.length && v.every((x) => typeof x === 'string')) return 'string[]';
    if (v.length && v.every((x) => Array.isArray(x))) return 'unknown[][]';
    return 'unknown[]';
  }
  if (v === null) return 'unknown';
  if (typeof v === 'object') return 'Record<string, unknown>';
  return typeof v;
};
const doc = (s) => s.replace(/\*\//g, '*\\/');
let ts = `// Generated by scripts/gen-video-components.mjs from \`anikit-video info --components --json\`. Do not edit.

/** Every component kind (kebab-case; camelCase also works). */
export const COMPONENT_KINDS = ${JSON.stringify(components.map((c) => c.name))} as const;

/** A component kind name. */
export type ComponentKind = (typeof COMPONENT_KINDS)[number] | ${components.filter((c) => c.name.includes('-')).map((c) => `'${camel(c.name)}'`).join(' | ') || 'never'} | (string & {});

/** Props per kind: the keys of each kind's example are typed; every other prop is accepted (see docs/video/components.md). */
export interface ComponentPropsMap {
`;
for (const c of components) {
  const keys = Object.entries(c.example ?? {}).map(([k, v]) => `${k}?: ${tsType(v)}; `).join('');
  ts += `  /** ${doc(c.summary)} Example: \`${doc(JSON.stringify(c.example))}\` */\n  '${c.name}': { ${keys}[prop: string]: unknown };\n`;
}
ts += `}

/** Props for a kind (loose for unknown kinds). */
export type ComponentProps<K extends string> = K extends keyof ComponentPropsMap ? ComponentPropsMap[K] : Record<string, unknown>;
`;
writeFileSync(join(root, 'packages/anikit/src/video/components.ts'), ts);

let py = `"""Generated by packages/anikit/scripts/gen-video-components.mjs from \`anikit-video info --components --json\`. Do not edit."""

#: Every component kind (kebab-case; camelCase also works), with a one-line summary.
COMPONENT_KINDS = {
`;
for (const c of components) py += `    ${JSON.stringify(c.name)}: ${JSON.stringify(c.summary)},\n`;
py += `}
`;
writeFileSync(join(root, 'crates/anikit-py/python/anikit/_video_components.py'), py);
console.log(`${components.length} component kinds`);
