#!/usr/bin/env python3
"""Toolkit uptake audit: which spec keys and named features each eval output used, and what changed vs a base round.

    python3 scripts/uptake.py --round r2 --base r1      # writes docs/video/judge/rounds/r2/UPTAKE.md

A "feature" is a spec key (e.g. `textAnimator`, `camera`, `sfx`) or a named value of a typed field
(`type=shader`, `ease=outExpo`, `sfx=riser`, `font=Big Shoulders`, `preset=typewriter`), plus files the agent shipped
(.glsl shaders, font files). Reads spec.json from each round branch (claude/epic-ramanujan-qe7x4w-v-eval-<round>-<id>).
"""
import argparse, collections, json, subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
J = ROOT / "docs/video/judge"
BASE = "claude/epic-ramanujan-qe7x4w"
TYPED = ("type", "kind", "component", "effect", "filter", "font", "family", "look", "preset", "shader", "ease", "easing",
         "transition", "fx", "sfx", "material", "env", "light", "camera", "mode", "blend", "instrument", "style", "recipe")


def git(*a):
    return subprocess.run(["git", "-C", str(ROOT), *a], capture_output=True, text=True)


def features(round_, bid):
    br = f"{BASE}-v-eval-{round_}-{bid}"
    git("fetch", "-q", "origin", f"{br}:refs/remotes/origin/{br}")
    files = git("ls-tree", "-r", "--name-only", f"origin/{br}", f"deliverables/eval/{bid}/").stdout.split()
    specs = [f for f in files if f.endswith("spec.json")] or [f for f in files if f.endswith(".json") and "stats" not in f]
    if not specs:
        return None
    try:
        d = json.loads(git("show", f"origin/{br}:{specs[0]}").stdout)
    except json.JSONDecodeError:
        return None
    keys, named = collections.Counter(), collections.Counter()

    def walk(x):
        if isinstance(x, dict):
            for k, v in x.items():
                keys[k] += 1
                if k in TYPED and isinstance(v, str) and len(v) < 60:
                    named[f"{k}={v}"] += 1
                walk(v)
        elif isinstance(x, list):
            for v in x:
                walk(v)
    walk(d)
    shipped = sorted({Path(f).suffix for f in files if Path(f).suffix in (".glsl", ".wgsl", ".ttf", ".otf", ".woff2", ".png", ".jpg", ".svg", ".wav")})
    return {"keys": keys, "named": named, "shipped": shipped, "spec_bytes": len(git("show", f"origin/{br}:{specs[0]}").stdout)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--round", required=True)
    ap.add_argument("--base")
    a = ap.parse_args()
    briefs = json.loads((J / "briefs.json").read_text())
    rows, tot_new, tot_all, tot_base = [], collections.Counter(), collections.Counter(), collections.Counter()
    for b in briefs:
        f1 = features(a.round, b["id"])
        f0 = features(a.base, b["id"]) if a.base else None
        if not f1:
            rows.append(f"| {b['id']} | – | – | – | – | – |")
            continue
        s1 = set(f1["keys"]) | set(f1["named"])
        tot_all.update(s1)
        new = sorted(s1 - (set(f0["keys"]) | set(f0["named"]))) if f0 else []
        gone = sorted((set(f0["keys"]) | set(f0["named"])) - s1) if f0 else []
        if f0:
            tot_base.update(set(f0["keys"]) | set(f0["named"]))
        tot_new.update(new)
        rows.append(f"| {b['id']} | {len(f1['keys'])} keys, {len(f1['named'])} named | {f1['spec_bytes'] // 1024} KB | {' '.join(f1['shipped']) or '–'} | "
                    f"{', '.join(new[:14]) + (' …' if len(new) > 14 else '') or '–'} | {', '.join(gone[:8]) + (' …' if len(gone) > 8 else '') or '–'} |")
    title = f"# Toolkit uptake: {a.round}" + (f" vs {a.base}" if a.base else "")
    L = [title, "",
         "Which spec keys and named features (`type=`, `ease=`, `sfx=`, `font=`, `preset=` …) each output's spec.json used. "
         "Generated by `scripts/uptake.py`.", "",
         f"| Brief | Spec | Size | Shipped files | New vs {a.base or '-'} | Dropped vs {a.base or '-'} |", "|---|---|---|---|---|---|"] + rows
    L += ["", f"## Most used across {a.round} (number of briefs)", "", ", ".join(f"`{k}` {v}" for k, v in tot_all.most_common(60))]
    if a.base:
        L += ["", f"## Gained across briefs (used in {a.round}, not in {a.base} for that brief)", "",
              ", ".join(f"`{k}` {v}" for k, v in tot_new.most_common(50)) or "–",
              "", f"## Used in {a.round} by at least one brief but by no {a.base} brief", "",
              ", ".join(f"`{k}`" for k in sorted(set(tot_all) - set(tot_base))) or "–"]
    out = J / "rounds" / a.round / "UPTAKE.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
